import { toUserMessage } from '../lib/errors';
import { supabase } from '../lib/supabase';
import { Course, CourseListItem } from '../types/database';
import { AppError } from '../types/domain';

export interface CreateCourseParams {
  code: string;
  title: string;
  description?: string | null;
}

export interface EnrolledStudent {
  id: string;
  full_name: string;
}

const COURSE_SELECT_FIELDS = `
  id,
  code,
  title,
  description,
  join_code,
  instructor_id,
  created_at,
  instructor:profiles!instructor_id(full_name),
  materials(count),
  enrollments(count)
`;

/**
 * Retrieves all courses accessible to the authenticated user.
 * Scoped automatically by database RLS (SEC-7): instructors see their created courses,
 * while students see courses they are actively enrolled in.
 */
export async function listCourses(): Promise<CourseListItem[]> {
  const { data, error } = await supabase
    .from('courses')
    .select(COURSE_SELECT_FIELDS)
    .order('created_at', { ascending: false });

  if (error) {
    throw new AppError(error.code ?? 'LIST_COURSES_FAILED', toUserMessage(error), error);
  }

  return (data as unknown as CourseListItem[]) ?? [];
}

/**
 * Retrieves a single course by its ID.
 * Throws a user-friendly AppError if the course does not exist or user lacks access.
 */
export async function getCourse(id: string): Promise<CourseListItem> {
  const { data, error } = await supabase
    .from('courses')
    .select(COURSE_SELECT_FIELDS)
    .eq('id', id)
    .single();

  if (error || !data) {
    throw new AppError('COURSE_NOT_FOUND', 'Course not found. It may have been deleted.', error);
  }

  return data as unknown as CourseListItem;
}

/**
 * Creates a new course under the authenticated instructor's ID.
 * Join code is auto-generated by the database default function.
 */
export async function createCourse(params: CreateCourseParams): Promise<Course> {
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    throw new AppError('UNAUTHENTICATED', 'You must be signed in to create a course.');
  }

  const { data, error } = await supabase
    .from('courses')
    .insert({
      code: params.code.trim().toUpperCase(),
      title: params.title.trim(),
      description: params.description?.trim() || null,
      instructor_id: user.id,
    })
    .select('id, code, title, description, instructor_id, join_code, created_at')
    .single();

  if (error) {
    throw new AppError(error.code ?? 'CREATE_COURSE_FAILED', toUserMessage(error), error);
  }

  return data as Course;
}

/**
 * Lists all storage paths under a specific bucket folder.
 * Recursively inspects subdirectories for nested submission paths.
 */
async function listStorageFolderFiles(bucket: string, folder: string): Promise<string[]> {
  const { data, error } = await supabase.storage.from(bucket).list(folder);

  if (error || !data) {
    return [];
  }

  const paths: string[] = [];
  for (const item of data) {
    // Supabase Storage reports folders with id: null
    if (item.id === null) {
      const nested = await listStorageFolderFiles(bucket, `${folder}/${item.name}`);
      paths.push(...nested);
    } else {
      paths.push(`${folder}/${item.name}`);
    }
  }

  return paths;
}

/**
 * Safe multi-step deletion for an entire course (FH-3).
 * Step 1: Lists all files in `lms-files/{courseId}/` and `submission-files/{courseId}/`.
 * Step 2: Removes all listed storage files across both private buckets.
 * Step 3: Deletes the database course row, triggering ON DELETE CASCADE on relations.
 */
export async function deleteCourse(courseId: string): Promise<void> {
  const [lmsFiles, submissionFiles] = await Promise.all([
    listStorageFolderFiles('lms-files', courseId),
    listStorageFolderFiles('submission-files', courseId),
  ]);

  // Storage cleanup is best-effort before cascading database rows
  if (lmsFiles.length > 0) {
    const { error } = await supabase.storage.from('lms-files').remove(lmsFiles);
    if (error) {
      // Diagnostic warning allowed per P3.1 guidelines (never logs sensitive data)
      console.warn(`LMS storage cleanup warning for course ${courseId}: ${error.message}`);
    }
  }

  if (submissionFiles.length > 0) {
    const { error } = await supabase.storage.from('submission-files').remove(submissionFiles);
    if (error) {
      console.warn(`Submissions storage cleanup warning for course ${courseId}: ${error.message}`);
    }
  }

  const { error: dbError } = await supabase
    .from('courses')
    .delete()
    .eq('id', courseId);

  if (dbError) {
    throw new AppError(dbError.code ?? 'DELETE_COURSE_FAILED', toUserMessage(dbError), dbError);
  }
}

/**
 * Retrieves the list of students enrolled in a specific course.
 * Used by instructors to review class roster.
 */
export async function listEnrolledStudents(courseId: string): Promise<EnrolledStudent[]> {
  const { data, error } = await supabase
    .from('enrollments')
    .select('student:profiles!student_id(id, full_name)')
    .eq('course_id', courseId);

  if (error) {
    throw new AppError(error.code ?? 'LIST_STUDENTS_FAILED', toUserMessage(error), error);
  }

  interface StudentEnrollmentRow {
    student: EnrolledStudent | null;
  }

  const rows = (data as unknown as StudentEnrollmentRow[]) ?? [];
  return rows
    .map((row) => row.student)
    .filter((student): student is EnrolledStudent => student !== null);
}

/**
 * Removes a student from a course enrollment (instructor-only action, enforced by RLS).
 */
export async function removeStudent(courseId: string, studentId: string): Promise<void> {
  const { error } = await supabase
    .from('enrollments')
    .delete()
    .eq('course_id', courseId)
    .eq('student_id', studentId);

  if (error) {
    throw new AppError(error.code ?? 'REMOVE_STUDENT_FAILED', toUserMessage(error), error);
  }
}

